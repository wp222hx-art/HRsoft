const DICTS: Record<Lang, Dict> = { zh, en };

/** Look up a translation key. Falls back to the key itself if missing. */
export function lookup(lang: Lang, key: string): string {
  return DICTS[lang]?.[key] ?? DICTS.zh[key] ?? key;
}

/** Simple {placeholder} interpolation. */
export function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Translate function — used by both client and server components. */
export function makeT(lang: Lang) {
  return (key: string, vars?: Record<string, string | number>) =>
    interpolate(lookup(lang, key), vars);
}
